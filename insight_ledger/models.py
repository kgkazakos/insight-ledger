"""Core dataclasses for insight-ledger."""

from __future__ import annotations

import uuid
from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Optional


class LinkStatus(str, Enum):
    ADOPTED = "adopted"
    PARTIAL = "partial"
    DECLINED = "declined"
    DEFERRED = "deferred"
    PENDING = "pending"
    PROPOSED = "proposed"      # auto-generated, awaiting human arbitration


class LinkStrength(str, Enum):
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class DecisionType(str, Enum):
    FEATURE = "feature"
    DESIGN = "design"
    PRIORITY = "priority"
    STRATEGY = "strategy"
    PROCESS = "process"
    KILL = "kill"


@dataclass
class Insight:
    """A research insight that may inform product decisions."""

    id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    title: str = ""
    summary: str = ""
    study_name: str = ""
    study_date: Optional[str] = None
    researcher: str = ""
    tags: list[str] = field(default_factory=list)
    raw_evidence: str = ""
    confidence: float = 0.8

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class Decision:
    """A product or design decision made by the team."""

    id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    title: str = ""
    description: str = ""
    decision_type: str = DecisionType.FEATURE.value
    decision_date: Optional[str] = None
    owner: str = ""
    team: str = ""
    reference: str = ""          # free-form: doc URL, spec title, brief ID — no tool coupling
    outcome_notes: str = ""

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class InsightLink:
    """
    A link connecting an Insight to a Decision.

    May be manually logged (auto_proposed=False) or LLM-proposed and
    awaiting human arbitration (auto_proposed=True, status='proposed').
    """

    id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    insight_id: str = ""
    decision_id: str = ""
    status: str = LinkStatus.ADOPTED.value
    strength: str = LinkStrength.HIGH.value
    rationale: str = ""              # researcher's words (or LLM rationale for proposals)
    logged_by: str = ""
    logged_date: Optional[str] = None
    llm_note: Optional[str] = None   # optional LLM provenance sentence (manual links)
    auto_proposed: bool = False      # True = generated by propose command
    proposal_confidence: float = 0.0 # LLM confidence score (0–1), proposals only

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class LedgerRecord:
    """Resolved record joining a link with its insight and decision."""

    link: InsightLink
    insight: Insight
    decision: Decision

    @property
    def status(self) -> str:
        return self.link.status

    @property
    def strength(self) -> str:
        return self.link.strength

    @property
    def is_proposed(self) -> bool:
        return self.link.auto_proposed and self.link.status == LinkStatus.PROPOSED.value

    def to_dict(self) -> dict:
        return {
            "link": self.link.to_dict(),
            "insight": self.insight.to_dict(),
            "decision": self.decision.to_dict(),
        }


@dataclass
class LedgerSummary:
    """Aggregate statistics for a ledger corpus."""

    total_insights: int = 0
    total_decisions: int = 0
    total_links: int = 0          # confirmed links only (excludes proposed)
    proposed_count: int = 0       # links awaiting arbitration
    adopted: int = 0
    partial: int = 0
    declined: int = 0
    deferred: int = 0
    pending: int = 0
    high_strength: int = 0
    medium_strength: int = 0
    low_strength: int = 0
    activation_rate: float = 0.0  # (adopted + 0.5*partial) / (adopted+partial+declined)
    top_researchers: list[str] = field(default_factory=list)
    top_teams: list[str] = field(default_factory=list)
    top_tags: list[str] = field(default_factory=list)
    llm_narrative: Optional[str] = None

    def to_dict(self) -> dict:
        return asdict(self)
